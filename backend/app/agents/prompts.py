from app.agents.constants import FORBIDDEN_WORDS, FORBIDDEN_PATTERNS, FORBIDDEN_RULES, OUTLINE_FORBIDDEN_WORDS_BRIEF


def _format_forbidden_words() -> str:
    """格式化禁用词列表为 Prompt 可用格式"""
    words = "、".join(FORBIDDEN_WORDS)
    patterns = "\n".join(f"- {p}" for p in FORBIDDEN_PATTERNS)
    rules = "\n".join(f"- {r}" for r in FORBIDDEN_RULES)

    return f"""**绝对禁用词汇**：
{words}

**绝对禁用句式**：
{patterns}

**禁用规则**：
{rules}"""


def _format_forbidden_words_list() -> str:
    """格式化禁用词列表为逗号分隔的字符串（用于打分维度说明）"""
    return "、".join(FORBIDDEN_WORDS)


def _format_forbidden_words_brief() -> str:
    """格式化精简禁用词列表"""
    return "、".join(OUTLINE_FORBIDDEN_WORDS_BRIEF)


def _apply_forbidden_words_brief_to_prompt(prompt_template: str) -> str:
    """将精简禁用词格式化后注入到 prompt 模板中"""
    return prompt_template.replace("{forbidden_words_brief}", _format_forbidden_words_brief())


