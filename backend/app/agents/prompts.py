# Prompt 格式化工具
# ==============================================================================

def get_prompt_template(prompts: dict, name: str) -> tuple[str, str]:
    """获取 system/user 双层 prompt 模板

    Args:
        prompts: state["_prompts"] 字典
        name: prompt 名称

    Returns:
        (system_template, user_template) — 模板不存在则为 (None, None)
    """
    template = prompts.get(name)
    if template is None:
        return None, None
    if isinstance(template, dict):
        return template.get("system", ""), template.get("user", "")
    return "", str(template)
